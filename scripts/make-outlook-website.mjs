// Generates lib/fire-outlook-website.ts from the frozen lib/fire-outlook.ts with ONE change: the drought
// index (gridMET PDSI) may be up to 15 days older than the weather day instead of 5. The frozen file and
// the NOAA-20 trial are not touched; the website route uses this copy only when the strict outlook
// abstains for that single reason. Re-run after any change to lib/fire-outlook.ts:
//   node scripts/make-outlook-website.mjs
import { readFileSync, writeFileSync } from "node:fs";
const src = readFileSync("lib/fire-outlook.ts", "utf8");
const from = "Date.parse(dates.weatherDate)-Date.parse(grid.date)>5*DAY", to = "Date.parse(dates.weatherDate)-Date.parse(grid.date)>15*DAY";
if (src.split(from).length !== 2) throw new Error("Expected exactly one PDSI age rule in lib/fire-outlook.ts");
const header = "// GENERATED by scripts/make-outlook-website.mjs from lib/fire-outlook.ts. Do not edit by hand.\n// Only difference: PDSI may be up to 15 days older than the weather day (trial rule: 5 days).\n";
writeFileSync("lib/fire-outlook-website.ts", header + src.replace(from, to));
console.log("wrote lib/fire-outlook-website.ts");
